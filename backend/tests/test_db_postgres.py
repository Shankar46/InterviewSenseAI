from types import SimpleNamespace

from backend.db import _PostgresConnection


def test_postgres_connection_translates_sqlite_query_syntax():
    captured = {}

    def execute(query, parameters):
        captured["query"] = query
        captured["parameters"] = parameters
        return query, parameters

    connection = _PostgresConnection(SimpleNamespace(execute=execute))
    connection.execute(
        """SELECT ? FROM user_sessions
           WHERE expires_at > datetime('now', '+30 days')
             AND created_at = datetime('now')
             AND usage_date = date('now')""",
        (7,),
    )

    assert captured["parameters"] == (7,)
    assert "%s" in captured["query"]
    assert "CURRENT_TIMESTAMP + INTERVAL '+30 days'" in captured["query"]
    assert "created_at = CURRENT_TIMESTAMP" in captured["query"]
    assert "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::date" in captured["query"]


def test_postgres_connection_converts_sqlite_schema_types():
    captured = {}

    def execute(query, parameters):
        captured["query"] = query
        return query

    connection = _PostgresConnection(SimpleNamespace(execute=execute))
    connection.execute(
        """CREATE TABLE sample (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            created_at TEXT NOT NULL,
            usage_date TEXT NOT NULL
        )"""
    )

    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in captured["query"]
    assert "user_id BIGINT NOT NULL" in captured["query"]
    assert "created_at TIMESTAMPTZ NOT NULL" in captured["query"]
    assert "usage_date DATE NOT NULL" in captured["query"]
