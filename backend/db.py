def _migrate_auth(conn):
    """Add the account-hardening columns to databases created before they existed.
    Runs on SQLite and Postgres (the older _migrate only handles SQLite)."""
    if USE_POSTGRES:
        conn.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS username_lower TEXT")
        conn.execute("ALTER TABLE user_sessions ADD COLUMN IF NOT EXISTS user_agent TEXT NOT NULL DEFAULT ''")
    else:
        user_cols = {row[1] for row in conn.execute("PRAGMA table_info(users)").fetchall()}
        if "username_lower" not in user_cols:
            conn.execute("ALTER TABLE users ADD COLUMN username_lower TEXT")
        sess_cols = {row[1] for row in conn.execute("PRAGMA table_info(user_sessions)").fetchall()}
        if "user_agent" not in sess_cols:
            conn.execute("ALTER TABLE user_sessions ADD COLUMN user_agent TEXT NOT NULL DEFAULT ''")

    conn.execute("UPDATE users SET username_lower = lower(username) WHERE username_lower IS NULL")

    # Case-insensitive uniqueness ("Alice" and "alice" must not both exist). If an old
    # database already has such a pair, do NOT crash startup: skip the index, warn, and
    # let register_user's own check keep new duplicates out.
    clash = conn.execute(
        "SELECT username_lower FROM users GROUP BY username_lower HAVING COUNT(*) > 1"
    ).fetchall()
    if clash:
        logger.warning("Accounts differ only by letter case (%d clash(es)); "
                       "case-insensitive unique index NOT created. Merge or rename them.", len(clash))
    else:
        conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower ON users(username_lower)")


def _migrate(conn):
    """Non-destructive schema migrations for existing databases."""
    if USE_POSTGRES:
        return

    # Check users table schema
    users_existing = {row[1] for row in conn.execute("PRAGMA table_info(users)").fetchall()}
    if users_existing and "username" not in users_existing:
        logger.info("Migrating legacy users table to new schema...")
        conn.execute("ALTER TABLE users RENAME TO users_old")
        
        # Rename dependent tables to update/clear foreign key references
        conn.execute("ALTER TABLE user_sessions RENAME TO user_sessions_old")
        conn.execute("ALTER TABLE user_chats RENAME TO user_chats_old")
        
        conn.execute("""
            CREATE TABLE users (
                user_id         INTEGER PRIMARY KEY AUTOINCREMENT,
                username        TEXT UNIQUE NOT NULL,
                password_hash   TEXT NOT NULL,
                created_at      TEXT NOT NULL DEFAULT (datetime('now'))
            )
        """)
        
        conn.execute("""
            CREATE TABLE user_sessions (
                session_token   TEXT PRIMARY KEY,
                user_id         INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                created_at      TEXT NOT NULL DEFAULT (datetime('now')),
                expires_at      TEXT NOT NULL
            )
        """)
        
        conn.execute("""
            CREATE TABLE user_chats (
                chat_id         TEXT PRIMARY KEY,
                user_id         INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE
            )
        """)
        
        has_email = "email" in users_existing
        has_password = "password" in users_existing
        has_id = "id" in users_existing
        
        select_id = "id" if has_id else "NULL"
        select_username = "email" if has_email else "''"
        select_password = "password" if has_password else "''"
        select_created = "created_at" if "created_at" in users_existing else "(datetime('now'))"
        
        conn.execute(f"""
            INSERT INTO users (user_id, username, password_hash, created_at)
            SELECT {select_id}, {select_username}, {select_password}, {select_created} FROM users_old
        """)
        
        # Copy data for dependent tables if any existed
        conn.execute("""
            INSERT INTO user_sessions (session_token, user_id, created_at, expires_at)
            SELECT session_token, user_id, created_at, expires_at FROM user_sessions_old
        """)
        conn.execute("""
            INSERT INTO user_chats (chat_id, user_id)
            SELECT chat_id, user_id FROM user_chats_old
        """)
        
        conn.execute("DROP TABLE users_old")
        conn.execute("DROP TABLE user_sessions_old")
        conn.execute("DROP TABLE user_chats_old")
        logger.info("Legacy users and dependent tables migrated successfully.")

    existing = {row[1] for row in conn.execute("PRAGMA table_info(course_sessions)").fetchall()}
    migrations = {
        "day_plan":    "ALTER TABLE course_sessions ADD COLUMN day_plan TEXT DEFAULT '[]'",
        "created_at":  "ALTER TABLE course_sessions ADD COLUMN created_at TEXT DEFAULT (datetime('now'))",
        "updated_at":  "ALTER TABLE course_sessions ADD COLUMN updated_at TEXT DEFAULT (datetime('now'))",
    }
    for col, sql in migrations.items():
        if col not in existing:
            conn.execute(sql)

    prog_existing = {row[1] for row in conn.execute("PRAGMA table_info(progress)").fetchall()}
    prog_migrations = {
        "completion_date": "ALTER TABLE progress ADD COLUMN completion_date TEXT",
        "score":           "ALTER TABLE progress ADD COLUMN score INTEGER",
        "notes":           "ALTER TABLE progress ADD COLUMN notes TEXT",
    }
    for col, sql in prog_migrations.items():
        if col not in prog_existing:
            try:
                conn.execute(sql)
            except Exception as e:
                logger.warning("Migration skipped for '%s': %s", col, e)



# ── Session state ────────────────────────────────────────────

def save_session_state(chat_id: str, state: dict):
    plan_json = json.dumps(state.get("day_plan", []))
    with get_connection() as conn:
        conn.execute("""
            INSERT INTO course_sessions
                (chat_id, role, duration_days, hours_per_day, level, dsa_track,
                 current_day, started, awaiting_answers, last_quiz, day_plan, updated_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, datetime('now'))
            ON CONFLICT(chat_id) DO UPDATE SET
                role             = excluded.role,
                duration_days    = excluded.duration_days,
                hours_per_day    = excluded.hours_per_day,
                level            = excluded.level,
                dsa_track        = excluded.dsa_track,
                current_day      = excluded.current_day,
                started          = excluded.started,
                awaiting_answers = excluded.awaiting_answers,
                last_quiz        = excluded.last_quiz,
                day_plan         = excluded.day_plan,
                updated_at       = datetime('now')
        """, (
            chat_id,
            state["role"],
            int(state["duration_days"]),
            str(state["hours_per_day"]),
            state["level"],
            "yes" if state.get("dsa_track") else "no",
            int(state["current_day"]),
            1 if state.get("started") else 0,
            1 if state.get("awaiting_answers") else 0,
            state.get("last_quiz", ""),
            plan_json,
        ))


def load_session_state(chat_id: str) -> dict | None:
    with get_connection() as conn:
        row = conn.execute(
            """SELECT role, duration_days, hours_per_day, level, dsa_track,
                      current_day, started, awaiting_answers, last_quiz, day_plan
               FROM course_sessions WHERE chat_id = ?""",
            (chat_id,),
        ).fetchone()
    if not row:
        return None
    return {
        "role":             row["role"],
        "duration_days":    row["duration_days"],
        "hours_per_day":    row["hours_per_day"],
        "level":            row["level"],
        "dsa_track":        row["dsa_track"] == "yes",
        "current_day":      row["current_day"],
        "started":          row["started"] == 1,
        "awaiting_answers": row["awaiting_answers"] == 1,
        "last_quiz":        row["last_quiz"] or "",
        "day_plan":         _safe_json_list(row["day_plan"]),
    }


def _delete_chat_rows(conn, chat_id: str) -> None:
    # Every table keyed by chat_id. (The interview tables used to be missed here, so
    # deleting a chat left its mock-interview answers behind.)
    for table in ("course_sessions", "progress", "notifications", "messages",
                  "interview_qa", "interview_sessions", "user_chats"):
        conn.execute(f"DELETE FROM {table} WHERE chat_id = ?", (chat_id,))


def delete_session(chat_id: str):
    with get_connection() as conn:
        _delete_chat_rows(conn, chat_id)


def delete_user_account(user_id: int) -> None:
    """Permanently remove an account and everything that belongs to it, in one transaction."""
    with get_connection() as conn:
        chats = [r["chat_id"] for r in conn.execute(
            "SELECT chat_id FROM user_chats WHERE user_id = ?", (user_id,)).fetchall()]
        for chat_id in chats:
            _delete_chat_rows(conn, chat_id)
        conn.execute("DELETE FROM shared_key_usage WHERE user_id = ?", (user_id,))
        conn.execute("DELETE FROM user_sessions WHERE user_id = ?", (user_id,))
        conn.execute("DELETE FROM users WHERE user_id = ?", (user_id,))


